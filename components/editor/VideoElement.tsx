"use client";

import {
    useEffect,
    useRef,
    useState,
    type CSSProperties,
    type HTMLAttributes,
} from "react";

interface VideoElementProps extends HTMLAttributes<HTMLDivElement> {
    source?: string;
    poster?: string;
    controls?: boolean;
    autoPlay?: boolean;
    muted?: boolean;
    loop?: boolean;
    preload?: "auto" | "metadata" | "none";
    className?: string;
    style?: CSSProperties;
}

export default function VideoElement({
    source,
    poster,
    controls = true,
    autoPlay = false,
    muted = true,
    loop = false,
    preload = "metadata",
    className,
    style,
    ...interactionProps
}: VideoElementProps) {
    const videoRef = useRef<HTMLVideoElement | null>(null);
    const [isPlaying, setIsPlaying] = useState(false);

    useEffect(() => {
        const video = videoRef.current;
        if (!video) return;

        const syncPlayingState = () => {
            setIsPlaying(!video.paused && !video.ended);
        };

        video.addEventListener("play", syncPlayingState);
        video.addEventListener("pause", syncPlayingState);
        video.addEventListener("ended", syncPlayingState);

        return () => {
            video.removeEventListener("play", syncPlayingState);
            video.removeEventListener("pause", syncPlayingState);
            video.removeEventListener("ended", syncPlayingState);
        };
    }, [source]);

    async function togglePlayback() {
        const video = videoRef.current;
        if (!video) return;

        try {
            if (video.paused || video.ended) {
                await video.play();
            } else {
                video.pause();
            }
        } catch {
            // Browser autoplay / media policy can reject play().
        }
    }

    const videoStyle: CSSProperties = {
        position: "absolute",
        inset: 0,
        width: "100%",
        height: "100%",
        display: "block",
        maxWidth: "none",
        objectFit:
            style?.objectFit ??
            "cover",
        objectPosition:
            style?.objectPosition ??
            "center",
        pointerEvents: "none",
        userSelect: "none",
    };

    if (!source) {
        return (
            <div
                {...interactionProps}
                className={className}
                style={{
                    position: "relative",
                    minHeight: 180,
                    width: "100%",
                    overflow: "hidden",
                    display: "flex",
                    alignItems: "center",
                    justifyContent: "center",
                    backgroundColor: "#f3f4f6",
                    color: "#9ca3af",
                    fontSize: 14,
                    ...style,
                }}
                aria-label="Video placeholder"
            >
                Video
            </div>
        );
    }

    return (
        <div
            {...interactionProps}
            className={className}
            style={{
                position: "relative",
                overflow: "hidden",
                width: "100%",
                ...style,
            }}
        >
            <video
                ref={videoRef}
                src={source}
                poster={poster}
                controls={false}
                autoPlay={autoPlay}
                muted={muted}
                loop={loop}
                preload={preload}
                playsInline
                aria-label="Video"
                style={videoStyle}
                onLoadedMetadata={() => {
                    const video = videoRef.current;
                    if (video) {
                        setIsPlaying(!video.paused && !video.ended);
                    }
                }}
            />

            {/*
             * The native video controls intentionally stay disabled in the
             * editor because the canvas owns pointer events for selection,
             * dragging, and resizing. Preview mode still uses the real video
             * controls generated by Editor.tsx.
             */}
            {controls && (
                <button
                    type="button"
                    aria-label={
                        isPlaying
                            ? "Pause video"
                            : "Play video"
                    }
                    title={
                        isPlaying
                            ? "Pause video"
                            : "Play video"
                    }
                    onPointerDown={(event) => {
                        event.stopPropagation();
                    }}
                    onClick={(event) => {
                        event.stopPropagation();
                        void togglePlayback();
                    }}
                    style={{
                        position: "absolute",
                        left: "50%",
                        top: "50%",
                        transform: "translate(-50%, -50%)",
                        width: 52,
                        height: 52,
                        border: "1px solid rgba(255,255,255,0.7)",
                        borderRadius: "999px",
                        backgroundColor: "rgba(0,0,0,0.62)",
                        color: "#ffffff",
                        display: "flex",
                        alignItems: "center",
                        justifyContent: "center",
                        cursor: "pointer",
                        padding: 0,
                        zIndex: 2,
                        lineHeight: 1,
                        fontSize: 20,
                    }}
                >
                    {isPlaying ? "❚❚" : "▶"}
                </button>
            )}
        </div>
    );
}
